//! Метка кадра и ошибка приёма запроса исполнителем: общий словарь исполнителей оценки по статистике кадра.
//!
//! Раньше жили в `executor.rs` (исполнитель старого оценщика света); теперь их хозяин — AE: старый оценщик
//! удаляется, а метка и ошибка нужны замеру экспозиции ([`super::meter`]) в любом случае.

/// Чей кадр обрабатывается. Поля — то, что нужно вызывающему, чтобы привязать ответ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FrameTag {
    /// Поколение потока камеры у вызывающего (ответ чужого потока отбрасывается им же).
    pub stream_generation: u64,
    /// Порядковый номер кадра в потоке.
    pub sequence: u64,
    /// Метка сенсора кадра, наносекунды (шкала BOOTTIME).
    pub sensor_timestamp_nanos: i64,
}

/// Почему запрос не принят.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum SubmitError {
    /// Исполнитель занят и не принимает новых запросов (backpressure GPU-реализации): вызывающий
    /// пропускает кадр статистики — следующий придёт через несколько кадров.
    #[error("исполнитель оценки занят")]
    Busy,
}
