//! Автоэкспозиция и источники белого над статистикой RAW (сессии 08a, white-balance 01–03; решения 62–68).
//!
//! Crate нейтральный (без Vulkan и Android): его гоняют тесты на ПК, а исполняет поток рендера. Собственного
//! оценщика света сцены здесь больше нет (white-balance 03): белую продукта решает владелец белого в `camera-core`
//! (источники — «телефон», ручная), а этот crate даёт только то, что нужно ей и AE.
//!
//! # Состав
//! * [`white_source`] — источник белого: контракт «какой здесь свет» и источник «телефон» (white-balance 01);
//! * [`exposure`] — наш AE (08a, решения 63, 66, 68): статистика RAW → замер по плиткам (матричный и точечный),
//!   контроллер цели, предложение движку камеры и остаточная подтяжка ISP; форма исполнителя «отправить / забрать
//!   позже» (решение 68), порядок вызовов на кадр — в доке модуля;
//! * [`error`] — ошибка проверки конфигов этого crate.

pub mod error;
