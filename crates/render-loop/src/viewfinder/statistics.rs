//! Диагностика расписания статистики кадра на GPU (владелец расписания — `vulkan_backend::camera::statistics_schedule`).
//!
//! Статистика считается для потребителей (сегодня — только наш AE), а не «сама по себе»: пока потребителей нет,
//! диагностики тоже нет (`ViewfinderDiagnostics::statistics == None`). Проверки сценариев (ожидаемое число
//! публикаций) на этом и стоят: без AE на потоке рендера публикаций ноль, и это не поломка.

/// Расписание статистики одной сессии показа. Счётчики накопительные.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StatisticsDiagnostics {
    /// Установившийся период: на каждом N-м обработанном кадре статистика считается (конфиг
    /// `viewfinder.auto_exposure.statistics_every_n_frames`; 1 — на каждом).
    pub every_n_frames: u32,
    /// Сколько кадров включили стадию статистики (по периоду, по требованию «каждый кадр» и при скрытых кадрах).
    pub requested: u64,
    /// Сколько кадров с потребителем стадию пропустили: до следующего кадра периода статистика не нужна.
    pub skipped_by_period: u64,
}
