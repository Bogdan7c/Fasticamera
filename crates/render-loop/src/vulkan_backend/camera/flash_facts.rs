//! Факты о свете кадров, которые видоискатель отдаёт движку снимков для кадра со вспышкой (14d).
//!
//! Видоискатель — единственный, кто мерит кадры (статистика ISP) и знает, чем освещён каждый. Движок
//! снимков должен проверить по пикселям, что кадр со вспышкой освещён: для этого нужен свет сцены без вспышки.
//! Он и описан здесь простыми данными, без привязки к тому, кто его считает и кто читает (сессия лишь
//! передаёт его через ленту `StillFeed`). Белая кадра со вспышкой — не факт о сцене: её несёт план движка.

use std::sync::Arc;

use camera_contract::capture_result::SensorTimestamp;
use camera_contract::frame_passport::StreamPassport;

/// Уровень света сцены без вспышки: средний зелёный кадра на единицу «выдержка × ISO». Нужен проверке
/// «кадр со вспышкой освещён»: по нему предсказывается, каким был бы кадр без вспышки.
#[derive(Debug, Clone)]
pub struct AmbientLevel {
    pub stream: Arc<StreamPassport>,
    /// Кадр без светодиода, по которому измерено.
    pub frame: SensorTimestamp,
    /// Средний нормированный зелёный (0…1, чёрный вычтен, до баланса белого) / произведение кадра, с⁻¹ISO⁻¹.
    pub green_per_product: f64,
}
