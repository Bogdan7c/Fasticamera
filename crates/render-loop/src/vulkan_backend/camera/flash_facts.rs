//! Факты о свете кадров, которые видоискатель отдаёт движку снимков для кадра со вспышкой (14d).
//!
//! Видоискатель — единственный, кто мерит кадры (статистика ISP) и знает, чем освещён каждый. Движок
//! снимков должен проявить кадр со вспышкой с белой светодиода и проверить по пикселям, что кадр освещён.
//! Эти два вида фактов и описаны здесь простыми данными, без привязки к тому, кто их считает и кто читает
//! (сессия лишь передаёт их через ленту `StillFeed`).

use std::sync::Arc;

use camera_contract::capture_result::SensorTimestamp;
use camera_contract::frame_passport::StreamPassport;
use isp_model::color::chromaticity::Chromaticity;

/// Белая светодиода: НЕСГЛАЖЕННАЯ оценка света по кадру с фонариком предвспышки (тот же светодиод, что у
/// разовой вспышки). Берётся целиком из оценки одного кадра: сглаживание видоискателя тянуло бы её к свету сцены.
#[derive(Debug, Clone)]
pub struct TorchWhite {
    /// Поток кадра: годится только кадрам этого потока (таблица локуса у камер своя).
    pub stream: Arc<StreamPassport>,
    /// Кадр с фонариком, по которому оценена белая.
    pub frame: SensorTimestamp,
    pub white: Chromaticity,
}

/// Уровень света сцены без вспышки: средний зелёный кадра на единицу «выдержка × ISO». Нужен проверке
/// «кадр со вспышкой освещён»: по нему предсказывается, каким был бы кадр без вспышки.
#[derive(Debug, Clone)]
pub struct AmbientLevel {
    pub stream: Arc<StreamPassport>,
    /// Кадр без светодиода, по которому измерено.
    pub frame: SensorTimestamp,
    /// Средний нормированный зелёный (0…1, чёрный вычтен, до баланса белого) / произведение кадра, с⁻¹ISO⁻¹.
    pub green_per_product: f64,
}
