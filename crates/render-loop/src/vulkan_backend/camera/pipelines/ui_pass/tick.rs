//! UI одного тика, подготовленный ДО записи кадра (решение 214, сессия 16a).
//!
//! Раньше источник UI вызывался внутри записи кадра. Чтобы решить «рисовать ли тик, если картинка не изменилась»,
//! список рисования нужен раньше записи: его сравнивают с уже показанным. Поэтому подготовка (запрос к источнику)
//! и запись в GPU разделены: [`UiTick`] — итог первого шага и вход второго.
//!
//! Контракт источника не меняется: он по-прежнему вызывается ровно раз на каждый тик, который дошёл до кадра
//! (в том числе на тике, который потом пропущен как «ничего не изменилось»), — от этого зависят разбор касаний и
//! продвижение анимаций по времени показа.

use ui_draw::draw_list::DrawList;
use ui_draw::frame_source::BackdropContinuity;
use ui_draw::geometry::PxSize;

/// Что UI дал на этот тик.
#[derive(Debug, Clone, PartialEq)]
pub enum UiTick {
    /// Источника UI нет (или проход UI выключен): на экране только видоискатель.
    Inactive,
    /// Источник есть, но кадр UI получить не удалось (отказ источника, рендера, непригодный размер или цветовое
    /// пространство). Кадр идёт без UI, причина — в диагностике UI. Что именно на экране, неизвестно: сравнивать
    /// такой тик с показанным нельзя.
    Unavailable,
    /// Источник дал список, но запись UI подавлена замером A/B (`SuppressibleGpuWork::UiOverlayDrawing`): список
    /// выброшен, в GPU ничего не пишется.
    Suppressed,
    /// Список рисования получен и ждёт записи.
    Ready(ReadyUi),
}

/// Готовый к записи кадр UI: всё, от чего зависят его пиксели, кроме фона под стеклом.
#[derive(Debug, Clone, PartialEq)]
pub struct ReadyUi {
    /// Список рисования (`PartialEq` сравнивает все поля, влияющие на пиксели: элементы, свет, версии картинок).
    pub(super) draw_list: DrawList,
    /// Логический размер цели, под который источник построил список.
    pub(super) logical_px: PxSize,
    /// Пикселей на pt этого кадра (масштаб, под который источник построил список).
    pub(super) px_per_pt: f32,
    /// Что лежит под UI (живой кадр, удержанный, чёрный): UI рисует размытие перехода по этому значению.
    pub(super) continuity: BackdropContinuity,
}

#[cfg(test)]
impl ReadyUi {
    /// Собирает подготовленный кадр UI (рендер строит его в `prepare_ui_tick`; стенды и тесты — вручную).
    pub fn new(draw_list: DrawList, logical_px: PxSize, px_per_pt: f32, continuity: BackdropContinuity) -> Self {
        Self {
            draw_list,
            logical_px,
            px_per_pt,
            continuity,
        }
    }
}

/// Итог записи подготовленного UI в команды кадра.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UiRecordOutcome {
    /// Сколько раз не удалось записать метку времени (идёт в общий счётчик отказов замера кадра).
    pub timing_failures: u64,
    /// UI этого тика записан полностью. `false` — UI не рисовался вовсе (его не было, отказ рендера) или запись
    /// оборвалась: пиксели кадра нельзя считать «компоновка + этот список».
    pub drawn: bool,
}

impl UiRecordOutcome {
    /// Ничего не записано (UI не рисовался).
    pub(super) const NOT_RECORDED: Self = Self {
        timing_failures: 0,
        drawn: false,
    };
}
