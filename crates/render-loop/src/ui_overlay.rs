//! Рисование UI и стекла поверх живого видоискателя: словарь между приложением и потоком рендера
//! (сессия 11, решение 86).
//!
//! Здесь нет Vulkan. Модуль описывает только контракт:
//! * [`UiOverlayCommand`] — поставить источник кадра UI или снять его (идёт через почтовый ящик,
//!   `RenderInbox::ui_overlay_command`);
//! * [`UiOverlayOutcome`] — что бэкенд сделал с командой;
//! * [`UiOverlayDiagnostics`] — что UI делал: активный источник, счётчики, время GPU, последняя ошибка.
//!
//! Рисует UI `vulkan_backend::camera` (проход после компоновщика видоискателя). По умолчанию UI-проход
//! ВЫКЛЮЧЕН: без источника GPU-рендер UI даже не создаётся, кадр видоискателя идёт ровно как до сессии 11.
//!
//! Имена полей [`UiOverlayDiagnostics`] и вариантов [`UiOverlayCommand`] — внешний контракт (на них
//! написан сценарий `glass`): менять только вместе с потребителями.

use std::fmt;

use ui_draw::frame_source::UiFrameSource;

use crate::thread::DurationSummary;

/// Команда потоку рендера: источник кадра UI. Не `Copy` (владеет источником) и не сливается в ящике:
/// порядок `Install`/`Remove` сохраняется, каждая команда получает свой итог.
pub enum UiOverlayCommand {
    /// Поставить источник. Прежний источник (если был) заменяется и уничтожается на потоке рендера.
    /// Источник вызывается один раз на показанный кадр, на потоке рендера.
    Install(Box<dyn UiFrameSource>),
    /// Снять источник: дальше UI не рисуется. Объекты GPU рендера UI живут до отсоединения surface
    /// (их нельзя уничтожать, пока в полёте кадры, записанные с ними).
    Remove,
}

impl fmt::Debug for UiOverlayCommand {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Источник не обязан быть `Debug`: печатаем только его имя.
        match self {
            Self::Install(source) => formatter.debug_tuple("Install").field(&source.name()).finish(),
            Self::Remove => formatter.write_str("Remove"),
        }
    }
}

/// Что бэкенд сделал с командой [`UiOverlayCommand`]. Варианты разведены: «не поддержано» и «нечего
/// менять» вызывающему важно различать.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UiOverlayOutcome {
    /// Команда выполнена: источник поставлен (или заменён) либо снят.
    Applied,
    /// Команда ничего не изменила: `Remove` без установленного источника.
    AlreadyInEffect,
    /// Бэкенд не умеет рисовать UI: нет видоискателя камеры (тестовый паттерн, fake) или бэкенд
    /// неисправен. Источник при этом уничтожен.
    Unsupported,
}

/// Диагностика UI-прохода. Счётчики накопительные за жизнь бэкенда (переживают пересоздание surface);
/// окно времени GPU — скользящее (`viewfinder.gpu_time_window_frames`).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct UiOverlayDiagnostics {
    /// Имя установленного источника (`UiFrameSource::name`); `None` — UI не рисуется.
    pub active_source: Option<String>,
    /// Сколько раз источник поставлен (команд `Install`, принятых бэкендом).
    pub installs: u64,
    /// Сколько раз источник снят (`Remove` при установленном источнике; замена и сбои не считаются).
    pub removals: u64,
    /// Сколько кадров UI записано в команды кадра успешно.
    pub frames_drawn: u64,
    /// Сколько кадров UI не нарисовано из-за рендера (ошибка записи, превышение предела кадра, отказ
    /// создания рендера, непригодный масштаб). Видоискатель при этом показан как обычно.
    pub frames_failed: u64,
    /// Сколько раз источник отказал (`UiFrameError`): UI этого кадра не рисуется.
    pub source_failures: u64,
    /// Сколько кадров отвергнуто из-за превышения предела кадра (входят в `frames_failed`).
    pub limit_overflows: u64,
    /// Сколько раз пирамида размытия фона перестроена (новый кадр камеры).
    pub pyramid_rebuilds: u64,
    /// Сколько раз пирамида переиспользована без записи проходов (перекомпоновка того же кадра камеры).
    pub pyramid_reuses: u64,
    /// Сколько живых картинок (например, картинок цветовых приборов) нарисовано за все записанные кадры UI.
    pub live_images_drawn: u64,
    /// Сколько элементов-живых картинок пропущено, потому что картинки в кадре не было (прибор закрыт, ещё не
    /// записан): кадр UI при этом нарисован без этих элементов.
    pub live_images_missing: u64,
    /// Время UI на GPU: от «компоновка готова» до «UI готов», пирамида размытия включительно.
    /// `None` — замеров ещё нет.
    pub gpu_time: Option<DurationSummary>,
    /// Причина последнего сбоя (источник, рендер, создание рендера); `None` — сбоев не было.
    pub last_error: Option<String>,
}
