//! Ошибки цветовых приборов GPU. Все проверки идут ДО записи команд: при ошибке командный буфер не тронут.

use ash::vk;
use gpu_vulkan::error::GpuError;
use scope_contract::ScopeImageSize;
use scope_model::ScopeSettingsError;

use super::rule::AccumulatorId;

/// Почему прибор нельзя создать или записать.
#[derive(Debug, PartialEq, thiserror::Error)]
pub enum ScopeError {
    /// Конфигурация не имеет смысла.
    #[error("конфигурация приборов: {what}")]
    InvalidConfig {
        /// Что не так.
        what: String,
    },
    /// Слот кадра вне кольца.
    #[error("слот кадра {slot} вне 0..{slots}")]
    FrameSlotOutOfRange {
        /// Запрошенный слот.
        slot: usize,
        /// Число слотов.
        slots: usize,
    },
    /// Картинка прибора нужного размера не подготовлена: запись кадра объектов GPU не создаёт, картинку заранее
    /// готовит `ColorScopes::prepare_picture` (между кадрами).
    #[error(
        "картинка прибора {requested:?} не подготовлена (готова: {prepared:?}); вызовите prepare_picture до записи"
    )]
    PictureNotPrepared {
        /// Размер, который просит кадр.
        requested: ScopeImageSize,
        /// Размер действующей картинки (`None` — картинки нет).
        prepared: Option<ScopeImageSize>,
    },
    /// Настройки модели приборов недопустимы.
    #[error("настройки приборов: {0}")]
    Settings(#[from] ScopeSettingsError),
    /// Формат входной картинки не читается приборами (поддержаны 10-бит UNORM и fp16 выхода видоискателя).
    #[error("формат входной картинки {format:?} не поддержан приборами")]
    UnsupportedInputFormat {
        /// Формат картинки.
        format: vk::Format,
    },
    /// Окно чтения не подходит к картинке (пустое содержимое, больше картинки).
    #[error("окно входной картинки: {0}")]
    InputWindow(GpuError),
    /// Показанная картинка больше предела приборов.
    #[error("показанная картинка {width}×{height} больше предела приборов")]
    InputTooLarge {
        /// Ширина содержимого.
        width: u32,
        /// Высота содержимого.
        height: u32,
    },
    /// У прибора нет зарегистрированного шейдера накопления.
    #[error("шейдер накопления {id:?} не зарегистрирован")]
    UnknownAccumulator {
        /// Запрошенный идентификатор.
        id: AccumulatorId,
    },
    /// Шейдер накопления зарегистрирован дважды.
    #[error("шейдер накопления {id:?} зарегистрирован дважды")]
    DuplicateAccumulator {
        /// Повторившийся идентификатор.
        id: AccumulatorId,
    },
    /// Сетка прибора не помещается в буфер счётчиков, рассчитанный на настройки при создании.
    #[error("в сетке прибора {cells} ячеек, а буфер счётчиков рассчитан на {capacity}")]
    GridExceedsCounterCapacity {
        /// Ячеек у сетки прибора.
        cells: usize,
        /// Ячеек в буфере.
        capacity: usize,
    },
    /// Плоскостей у прибора больше, чем умеет шейдер показа.
    #[error("плоскостей у прибора {planes}, шейдер показа умеет не больше {max}")]
    TooManyPlanes {
        /// Плоскостей у прибора.
        planes: u32,
        /// Предел.
        max: u32,
    },
    /// Слов параметров прибора больше, чем место в буфере.
    #[error("параметров прибора {words} слов, места {capacity}")]
    TooManyRuleWords {
        /// Слов у прибора.
        words: usize,
        /// Предел.
        capacity: usize,
    },
    /// Цветов следа не столько же, сколько плоскостей.
    #[error("цветов следа {colors}, а плоскостей у прибора {planes}")]
    TraceColorCountMismatch {
        /// Цветов.
        colors: usize,
        /// Плоскостей.
        planes: u32,
    },
    /// Способ рисования следа требует иного числа плоскостей, чем у прибора.
    #[error("способ рисования {paint:?} требует плоскостей {required}, а у прибора {planes}")]
    PaintPlaneCountMismatch {
        /// Способ рисования.
        paint: scope_model::TracePaint,
        /// Сколько плоскостей он требует.
        required: u32,
        /// Сколько у прибора.
        planes: u32,
    },
    /// Способ «цвет по положению» без таблицы цветов: рисовать нечем.
    #[error("способ рисования ColorByPosition требует таблицу цветов по положению, а прибор её не отдал")]
    MissingPositionPalette,
    /// Примитивов сетки больше, чем место в буфере показа.
    #[error("примитивов сетки {count}, места {max}")]
    TooManyGraticulePrimitives {
        /// Примитивов.
        count: usize,
        /// Предел.
        max: usize,
    },
    /// Число уровней waveform/parade не помещается в знаковое слово шейдера («основа строки»).
    #[error("уровней у прибора {levels}: основа строки не помещается в знаковое слово шейдера")]
    LevelsOutOfRange {
        /// Уровней у прибора.
        levels: u32,
    },
    /// Ошибка GPU-набора.
    #[error("GPU: {0}")]
    Gpu(#[from] GpuError),
    /// Отпечаток выхода приборов не получен (кадров нет, картинки нет или чтение GPU не удалось).
    #[error("отпечаток выхода приборов: {what}")]
    OutputDigest {
        /// Что не так.
        what: String,
    },
    /// Прочитанные счётчики не сходятся с формой сетки (внутренняя ошибка; читает только `test-support`).
    #[error("чтение счётчиков: {what}")]
    CounterReadback {
        /// Что не так.
        what: String,
    },
}
