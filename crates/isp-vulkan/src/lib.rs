//! ISP на GPU (сессия 07): обработка RAW-кадра камеры compute-шейдерами Vulkan.
//!
//! Три конвейера:
//! * [`viewfinder`] — быстрый видоискатель: один слитый compute-проход по варианту `Preview`
//!   эталона `isp-model` (уровни → баланс → демозаик 2×2 → цвет → охват → тон → OETF) плюс
//!   статистика AWB в том же проходе. Паритет с `isp_model::pipeline::run_reference` — с явным
//!   допуском в тестах.
//! * [`quality`] — полнокадровый конвейер (демозаик Menon 2007, временной шумодав «на пробу»)
//!   для замера запаса под видео (V4 README); в продукт видоискателя не встраивается.
//! * [`photo`] — продуктовое проявление снимка (сессия 14): захват сырых отсчётов в буфер снимка и проявление
//!   quality-цепочки полосами по строкам между кадрами видоискателя, переиспользует части [`quality`].
//!
//! Коррекция виньетирования по карте усилений (`isp_model::lens_shading`) — одна реализация шейдера
//! (`shaders/lens_shading.glsl`) для всех трёх конвейеров; карта лежит в host-буфере ([`lens_shading_map`]).
//!
//! Crate не владеет кадрами камеры (только заимствует импортированный источник на время записи
//! команд) и ничего не знает о камере, кроме паспорта; Vulkan — только через публичный набор
//! `gpu-vulkan` (решение владельца в 07: никакого сырого `ash::Device`).

pub mod lens_shading_map;
