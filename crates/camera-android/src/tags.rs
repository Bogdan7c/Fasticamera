//! Числовые значения тегов Camera2 и перечислений — для нейтральной логики, которой на ПК
//! не из чего взять биндинги (bindgen работает только под Android).
//!
//! Значения сняты с заголовков NDK 30 (`camera/NdkCameraMetadataTags.h`). Чтобы опечатка не жила
//! молча, под Android каждая константа **сверяется на этапе компиляции** с биндингом bindgen
//! (`const _: () = assert!(..)` внутри макроса): разошлось — не соберётся ни `build`, ни
//! `clippy --target aarch64-linux-android`. Вендорские теги здесь не живут: их номера
//! выдаёт устройство по имени (`vendor`).

/// Тег метаданных: числовой код и имя из NDK (для сообщений об ошибках и диагностики).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Tag {
    /// Код тега, как в `uint32_t tag` NDK.
    pub code: u32,
    /// Имя константы NDK, например `ACAMERA_SENSOR_TIMESTAMP`.
    pub name: &'static str,
}

impl Tag {
    const fn new(code: u32, name: &'static str) -> Self {
        Self { code, name }
    }
}

/// Объявляет теги и (под Android) проверяет их по биндингам NDK.
macro_rules! ndk_tags {
    ($($(#[$doc:meta])* $name:ident = $code:literal => $ndk:ident;)*) => {
        $($(#[$doc])* pub const $name: Tag = Tag::new($code, stringify!($ndk));)*

        #[cfg(target_os = "android")]
        const _: () = {
            $(assert!(
                $name.code == camera_ndk_sys::$ndk as u32,
                concat!("числовое значение тега ", stringify!($ndk), " разошлось с заголовком NDK"),
            );)*
        };
    };
}

/// Объявляет значения перечислений и (под Android) проверяет их по биндингам NDK.
macro_rules! ndk_values {
    ($($(#[$doc:meta])* $name:ident: $ty:ty = $value:literal => $ndk:ident;)*) => {
        $($(#[$doc])* pub const $name: $ty = $value;)*

        #[cfg(target_os = "android")]
        const _: () = {
            $(assert!(
                $name as i128 == camera_ndk_sys::$ndk as i128,
                concat!("значение ", stringify!($ndk), " разошлось с заголовком NDK"),
            );)*
        };
    };
}

