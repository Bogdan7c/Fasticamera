//! Нейтральный словарь снимка (решение 143, механизм М4 `docs/ios-camera/feature-map.md`).
//!
//! Снимок проходит через четыре модуля, и у каждого своя ответственность:
//! * экран камеры (`camera-screen`) решает, ЧТО снять: соотношение, зум, RAW, формат — и когда нажали;
//! * рендер (`render-loop`) решает, КАКОЙ кадр сенсора снят (тот, что был на экране в момент нажатия),
//!   забирает его из кольца, копирует сырые данные и проявляет снимок на GPU;
//! * `photo-output` пишет файлы: DNG, основной HEIF/JPEG, запись в хранилище;
//! * приложение только соединяет их.
//!
//! Этот crate — общий язык между ними, без логики и без знаний о GPU, Android и файлах.
//! Модули:
//! * [`plan`] — план снимка: номер, нажатие, выбор кадра, кадрирование, поворот, набор выходов;
//! * [`frame_choice`] — какой кадр выбран и почему (точно тот, что был на экране, или замена с пометкой);
//! * [`shot`] — описание захваченного кадра и проявленные данные (сырые 16 бит, картинка RGBA8);
//! * [`develop`] — обмен рендера и записи: события проявления и цель кодера;
//! * [`phase`] — фазы завершения для экрана: «кадр захвачен», «сохранено», «ошибка»;
//! * [`thumbnail`] — миниатюра снимка для экрана: маленькая копия в обычной памяти, не итог снимка.

pub mod develop;
pub mod frame_choice;
pub mod phase;
pub mod plan;
pub mod shot;
pub mod thumbnail;
