//! `ui-draw` — «что рисовать» на экране камеры, без GPU (решение 86, сессия 11).
//!
//! Пара `ui-draw` ↔ `ui-render-vulkan` устроена как `isp-model` ↔ `isp-vulkan`: здесь словарь и
//! эталонные формулы на CPU, там — их исполнение шейдерами. Экран камеры (12) видит только этот crate
//! (guardrail `screen-no-camera2-no-draw` запрещает ему GPU-модули), поэтому вёрстка подписей тоже здесь:
//! ширина текста нужна раскладке экрана.
//!
//! # Состав
//! * [`geometry`] — точки, размеры и прямоугольники в пикселях экрана (`f32`), переход из pt `ui-core`;
//! * [`transform`] — аффинное преобразование «локальные координаты фигуры → пиксели экрана»;
//! * [`color`] — цвет в закодированных значениях экрана (как пишет ISP), прозрачность;
//! * [`shape`] — фигуры (непрерывное скругление iOS, капсула, круг) и их SDF — эталон для шейдера;
//! * [`glass`] — параметры материала `GlassStyle` и эталонные формулы стекла (линза, дисперсия, тон, блик);
//! * [`light`] — направление света для блика из наклона телефона, сглаживание по времени;
//! * [`draw_list`] — список рисования кадра: фигуры, группы стекла, текст, иконки в порядке рисования;
//! * [`frame_source`] — источник кадра UI: кто строит список рисования к каждому показу (на потоке рендера);
//! * [`scene_bridge`] — элемент сцены `ui-core` (pt) → преобразование фигуры в пикселях экрана;
//! * [`atlas`] — SDF-атлас глифов и иконок, построенный при сборке (решение 88);
//! * [`text`] — вёрстка строки по запечённым метрикам Inter (решение 87);
//! * [`icons`] — набор иконок, запечённых в атлас.
//!
//! Чего здесь нет: Vulkan, Android, знаний о камере (guardrail `ui-draw-neutral`).

pub mod atlas;
pub mod color;
pub mod draw_list;
pub mod frame_source;
pub mod geometry;
pub mod glass;
pub mod icons;
pub mod light;
pub mod scene_bridge;
pub mod shape;
pub mod text;
pub mod transform;
