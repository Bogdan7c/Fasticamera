//! Линейка-ручка (решение 84, правило второго использования): горизонтальная шкала со ступенями, жёлтой
//! отметкой и риской поярче на каждом «целом» шаге.
//!
//! Первым пользователем была линейка Exposure нижней карточки, вторым стали ручки раздела калибровки; общее
//! вынесено сюда, чтобы они не разошлись:
//! * [`FingerGate`] — «кто двигает шкалу»: палец или программа. Значение превращается в намерение экрана
//!   только пока его ведёт палец, движение от программы — эхо, оно гасится и считается (правило «без эха»);
//! * [`RulerControl`] — шкала `SnapScale` + затвор пальца + вид рисок одним элементом.
//!
//! Что значат числа шкалы (EV, ручка вида) и какое действие они порождают — знает экран, а не элемент.

mod control;
mod finger_gate;

pub use control::{RulerControl, RulerSpec};
pub use finger_gate::{FingerGate, GatedEvent};
