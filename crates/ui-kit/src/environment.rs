//! Окружение элемента: то, что экран передаёт при создании (токены, предпочтение движения, размер области).

use ui_core::time::MotionPreference;

use crate::tokens::UiKitTokens;

/// Окружение, общее для шкалы и карусели. Берётся «взаймы» только на время создания:
/// элемент копирует нужные числа и дальше токенов не держит.
#[derive(Debug, Clone, Copy)]
pub struct ElementEnvironment<'a> {
    /// Токены движения, плотности и хаптики.
    pub tokens: &'a UiKitTokens,
    /// Предпочтение движения: при `Reduced` пружины без перелёта.
    pub motion: MotionPreference,
    /// Размер видимой области вдоль оси, pt (от него зависит «резинка»). Приходит из раскладки экрана.
    pub viewport_extent_points: f64,
}
