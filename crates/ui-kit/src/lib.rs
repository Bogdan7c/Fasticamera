//! Переиспользуемые элементы экрана камеры (решение 84, каталог `docs/ios-camera/components.md`).
//!
//! Слой между механикой `ui-core` и сборкой экрана `camera-screen`. Элемент не знает предметной
//! области: [`scale`] — это «шкала с упорами», а не «колесо зума»; смысл значений задают модели
//! [`value`] и привязка на экране. Камеры, GPU и Android здесь нет (guardrail `ui-kit-not-camera`).
//!
//! # Состав
//! * [`value`] — модели значений: квантованная линейная, логарифмическая, ряд значений, кельвины + оттенок;
//! * [`scale`] — K3, шкала с упорами (зум, EV, ISO, выдержка, фокус, баланс — один элемент);
//! * [`button`] — K2, механика нажатия кнопки (подсветка при касании, срабатывание по отпусканию);
//! * [`carousel`] — K4, карусель с прилипанием (переключатель режимов, задел М1);
//! * [`picker`] — K5/K6, выбор из вариантов и переключатель-значок;
//! * [`drive`] — общий привод оси: знак/ось, начало отсчёта пальца, «поймать» едущий контент;
//! * [`pan`] — данные пана жеста → намерения элемента (один переход для экрана);
//! * [`environment`] — токены, предпочтение движения и размер области, передаваемые при создании;
//! * [`tokens`] — именованные пружины движения и таблица «событие → хаптика»: числа только здесь.
//!
//! Внешнего вида нет: элементы отдают состояние и события, рисует `ui-render-vulkan` (сессия 11).

pub mod button;
pub mod carousel;
pub mod drive;
pub mod environment;
mod event_queue;
pub mod pan;
pub mod picker;
pub mod scale;
pub mod tokens;
pub mod value;
