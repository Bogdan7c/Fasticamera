//! «Магнит нуля» под пальцем (решение 284): пока палец ведёт шкалу, значение на мгновение замирает на нуле.
//!
//! # Как это устроено
//! Зона «съедает» путь пальца, когда палец ПЕРЕСЕКАЕТ ноль (`HoldZone::applied_to`):
//! * до нуля значение идёт за пальцем 1:1 (на старте нет скачка, даже если ручка стоит далеко от нуля);
//! * дойдя до нуля, значение стоит нулём, пока палец проходит путь шириной `2 × half_width` (по `half_width`
//!   «вокруг нуля»); если ручка и так стояла на нуле, зона симметрична: по `half_width` в обе стороны;
//! * дальше значение снова идёт за пальцем, отставая от него на ширину зоны (вычитание зоны из пути).
//!
//! Почему вычитание, а не «отпустить значение на путь пальца у границы»: так положение непрерывно на выходе
//! из зоны (скачок на ширину зоны — ошибка). Цена: после прохода через ноль палец «опережает» значение на
//! `2 × half_width` (12 pt при зоне ±6 pt на мелкой шкале — 6 % хода ручки на 200 шагов); вернувшись через
//! ноль назад, палец отдаёт этот зазор обратно.
//!
//! # Чего магнит не делает
//! * Держит только палец (перетаскивание). Бросок после отпускания идёт по обычной проекции движка: быстрый
//!   взмах проходит нуль не задерживаясь, медленное отпускание в зоне оседает на нуле (ступень нуля —
//!   ближайшая точка прилипания).
//! * Щелчок нуля отдельно не рождается: у ступенчатой модели рубеж нулевой ступени — середина между шагами,
//!   поэтому единственный щелчок опорного значения звучит, когда значение СТАЛО нулём (не при входе в зону и
//!   не при оседании). Поэтому магнит доступен только ступенчатым моделям.

use super::error::ScaleError;
use crate::drive::HoldZone;

/// Магнит нуля шкалы. По умолчанию выключен: Exposure, белое и зум остаются как были.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub enum ZeroMagnet {
    /// Нет магнита: значение идёт за пальцем 1:1.
    #[default]
    Off,
    /// Держать ноль, пока палец проходит `±half_width_points` pt пути вокруг нулевого положения.
    Hold {
        /// Половина ширины зоны, pt пути пальца (строго больше нуля).
        half_width_points: f64,
    },
}

impl ZeroMagnet {
    /// Магнит шириной `±half_width_points`: `0` — выключен (значение из конфига «0 = выкл.»); отрицательное,
    /// бесконечное или не число — ошибка конфига, а не молчаливое «выкл.».
    pub fn hold_within(half_width_points: f64) -> Result<Self, ScaleError> {
        if !half_width_points.is_finite() || half_width_points < 0.0 {
            return Err(ScaleError::InvalidZeroMagnetWidth { half_width_points });
        }
        Ok(if half_width_points == 0.0 {
            ZeroMagnet::Off
        } else {
            ZeroMagnet::Hold { half_width_points }
        })
    }

    /// Зона в смещениях контента вокруг `zero_offset_points`; `None` — магнита нет.
    pub(crate) fn hold_zone(self, zero_offset_points: f64) -> Option<HoldZone> {
        match self {
            ZeroMagnet::Off => None,
            ZeroMagnet::Hold { half_width_points } => Some(HoldZone {
                centre_offset: zero_offset_points,
                half_width: half_width_points,
            }),
        }
    }
}
