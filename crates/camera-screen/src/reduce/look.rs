//! Вид картинки и пресеты: экран только пересылает намерение (решение 178).
//!
//! Инвариант модуля: редьюсер НЕ хранит вид и не проверяет значения пресетов. Что можно, а что нельзя
//! (имя занято, встроенный пресет не удалить) знает библиотека пресетов, она же и отвечает ошибкой; экран
//! 14b покажет эту ошибку по её варианту. Поэтому здесь нет ни отказов, ни изменения состояния экрана.

use look_contract::LookIntent;

use super::Ctx;
use crate::effect::Effect;
use crate::outcome::ActionOutcome;

/// Намерение по виду уходит наружу ровно одним эффектом, без изменений и без отказов.
pub(super) fn on_look(ctx: &mut Ctx<'_>, intent: LookIntent) -> ActionOutcome {
    ctx.emit(Effect::Look(intent));
    ActionOutcome::Applied
}
