//! Политика видоискателя: как кадры камеры раздаются рендеру по одному на vsync (решения 40, 53).
//!
//! # Зачем две политики
//! Кадры камеры приходят неровно: на OnePlus 11 возраст кадра при приходе 27–43 мс, то есть разброс
//! почти в период 60 Гц. Иногда между двумя тиками vsync приходят два кадра, иногда ни одного.
//! * [`ViewfinderPacing::LatestWins`] (сессия 05) — в ячейке только самый свежий кадр. Два кадра
//!   между тиками — старший вытесняется (`dropped_superseded`), а на следующем тике показывать нечего
//!   (повтор). На телефоне так терялось ~5 % кадров, на ПК-стенде ~16 % — видимое подёргивание.
//! * [`ViewfinderPacing::JitterBuffer`] (решение 53) — очередь с запасом: каждый тик рендер берёт
//!   САМЫЙ СТАРЫЙ непоказанный кадр, а запас покрывает тик без прихода. Каждый кадр сенсора
//!   показывается ровно один раз (обещание решения 36) ценой около одного кадра задержки.
//!
//! # Семантика буфера (`reserve`, `max_queued`)
//! * Заполнение (priming): после начала потока, смены эпохи и переключения политики рендер не
//!   получает кадров, пока в очереди не наберётся `reserve + 1` кадр. Потом каждый опрос отдаёт
//!   старейший кадр, пока очередь не пуста. Это одноразовая цена старта: ~`reserve` тиков чёрного
//!   (или прежнего) изображения.
//! * Запас расходуется, а не охраняется: тик без прихода показывает запасной кадр (без повтора).
//!   Пустая очередь у заполненного буфера — настоящий повтор кадра, он считается
//!   (`viewfinder_underruns`); заново ждать заполнения не нужно — пропущенный опрос сам поднимает
//!   уровень очереди на один кадр (опросов стало меньше, чем приходов).
//! * Переполнение: если после прихода в очереди больше `max_queued` кадров, старейший отпускается
//!   нетронутым (`dropped_jitter_overflow`, отдельно от `dropped_superseded`). Так очередь не копит
//!   задержку: часы камеры (60,03 к/с) чуть быстрее экрана (60,00 Гц), и раз в ~33 с лишний кадр
//!   неизбежно уходит — это и есть «неизбежный остаток» решения 53.
//! * Кадр старше уже выданного (публикация не по порядку прихода из-за ожидания пары) не выдаётся
//!   никогда: показ шёл бы назад во времени. Он считается вытесненным (`dropped_superseded`).

use serde::{Deserialize, Serialize};

/// Как видоискатель получает кадры потока (конфиг `camera.raw_stream.viewfinder_pacing`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ViewfinderPacing {
    /// Самый свежий кадр побеждает (сессия 05): минимальная задержка, вытеснения при неровном приходе.
    LatestWins,
    /// Буфер с запасом (решение 53): каждый кадр ровно один раз, ~1 кадр задержки. По умолчанию.
    #[default]
    JitterBuffer,
}

/// Параметры буфера видоискателя (конфиг `camera.raw_stream.viewfinder_jitter_buffer`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct JitterBufferConfig {
    /// Сколько кадров держать в запасе после заполнения. 1 — разброс прихода на телефоне чуть меньше
    /// периода 60 Гц, поэтому между тиками бывает не больше двух приходов и не меньше нуля: одного
    /// запасного кадра хватает, чтобы закрыть тик без прихода.
    pub reserve: u32,
    /// Сколько кадров может ждать в очереди; лишний старейший отпускается (`dropped_jitter_overflow`).
    /// 2 = запас + один «пришедший парой» кадр. Каждая ячейка — буфер камеры в плане пула.
    pub max_queued: u32,
}

impl Default for JitterBufferConfig {
    fn default() -> Self {
        Self {
            reserve: 1,
            max_queued: 2,
        }
    }
}

/// Итог переключения политики на ходу ([`crate::RawFrameStream::set_viewfinder_pacing`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ViewfinderPacingSwitch {
    /// Политика сменилась: очередь перестроена без потерь лизингов, буфер заново заполняется.
    Switched,
    /// Эта политика уже действовала — ничего не изменилось.
    AlreadyActive,
}
