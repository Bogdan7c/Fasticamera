//! Вёрстка экрана камеры: якоря и стеки (без универсального flexbox).
//!
//! Раскладка iPhone привязана к низу экрана (`docs/ios-camera/layout.md`, раздел 4.2): наш экран
//! выше эталона на 26,7 pt, и лишнее должно уйти в чёрную полосу сверху. Поэтому главный
//! инструмент — привязка к краю с отступом ([`AxisPlacement::End`]), а не пропорции.
//!
//! # Модель
//! * У каждого не-корневого элемента есть [`Placement`]: либо **якорь** относительно опорной
//!   области родителя ([`AnchorRule`]), либо **место в стеке** родителя ([`Placement::InStack`]
//!   с фиксированным размером).
//! * У каждого элемента есть [`ContainerLayout`]: как он размещает детей — свободно (по якорям
//!   детей) или стеком ([`StackSpec`]). Дети свободного контейнера обязаны быть с якорями, дети
//!   стека — со стековым размещением; несовпадение — [`LayoutError::PlacementMismatch`].
//! * Опорная область ([`ReferenceArea`]): рамка родителя или его безопасная зона (рамка минус
//!   `safe_insets` родителя; у корня это безопасная зона экрана).
//! * [`UiTree::layout`] считает абсолютные рамки в pt за один проход, детерминированно, и
//!   применяет результат **только если вся вёрстка прошла без ошибок** (иначе рамки не меняются).
//!
//! # Правила краевых случаев
//! * Отрицательный/нечисловой размер или отступ-длина, отрицательный промежуток стека,
//!   растяжение с отрицательной итоговой длиной — явные ошибки, а не нули.
//! * Скрытые элементы место в вёрстке занимают (как `isHidden` в UIKit-стеке без авто-схлопывания).
//! * Содержимое стека больше области не обрезается: оно выходит за область (при выравнивании
//!   по центру/концу — в сторону начала), решение о прокрутке принимает экран.

