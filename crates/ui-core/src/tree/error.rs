//! Ошибки дерева элементов.

use thiserror::Error;

use crate::geometry::Insets;
use crate::id::NodeId;

/// Ошибка операции над [`super::UiTree`].
///
/// Все ошибки — явные: чужой элемент вместо устаревшего идентификатора и «тихая» обрезка значений
/// недопустимы (жест или анимация, пережившие элемент, должны получить отказ, а не соседа).
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum TreeError {
    /// Идентификатор не указывает на живой элемент: его никогда не было, он удалён, или место
    /// уже занято новым элементом с другим поколением.
    #[error("элемент {0:?} не существует (удалён или идентификатор устарел)")]
    UnknownNode(NodeId),
    /// Корень экрана не удаляется: он живёт, пока живо дерево.
    #[error("корень дерева удалить нельзя")]
    CannotRemoveRoot,
    /// У корня нет правила размещения: его рамка — это экран, а не результат вёрстки.
    #[error("у корня нет правила размещения: его рамка задаётся размером экрана")]
    RootHasNoPlacement,
    /// Индекс вставки больше числа детей (вставка в позицию `child_count` равна вставке в конец).
    #[error("индекс вставки {index} больше числа детей {child_count} у элемента {parent:?}")]
    ChildIndexOutOfRange {
        parent: NodeId,
        index: usize,
        child_count: usize,
    },
    /// В арене закончились номера мест (`u32`).
    #[error("в дереве слишком много элементов")]
    CapacityExceeded,
    /// Прозрачность вне [0, 1] или не число. Решение: ошибка, а не обрезка, чтобы баг анимации
    /// (например, перелёт пружины за 1) был виден, а не маскировался.
    #[error("прозрачность должна быть числом в [0, 1], получено {0}")]
    InvalidOpacity(f64),
    /// Масштаб не конечен или равен нулю по какой-либо оси (обратное преобразование хит-теста
    /// для нулевого масштаба не существует). Отрицательный масштаб допустим — это отражение.
    #[error("масштаб должен быть конечным и ненулевым, получено ({x}, {y})")]
    InvalidScale { x: f64, y: f64 },
    /// Поворот не конечен.
    #[error("поворот должен быть конечным числом радиан, получено {0}")]
    InvalidRotation(f64),
    /// Сдвиг не конечен.
    #[error("сдвиг должен состоять из конечных чисел, получено ({dx}, {dy})")]
    InvalidTranslation { dx: f64, dy: f64 },
    /// Расширение области касания содержит нечисловое значение.
    #[error("расширение области касания должно состоять из конечных чисел: {0:?}")]
    InvalidTouchOutset(Insets),
    /// Размер экрана или безопасная зона недопустимы (не конечны или размер отрицателен).
    #[error("размер экрана должен быть конечным и неотрицательным, безопасная зона — конечной")]
    InvalidScreen,
    /// Порог прозрачности хит-теста вне [0, 1].
    #[error("порог прозрачности хит-теста должен быть числом в [0, 1], получено {0}")]
    InvalidHitTestThreshold(f64),
}
