//! Ядро UI экрана камеры (сессия 10, решение 6): механика без GPU и без Android.
//!
//! Ощущение «как iPhone» — это прежде всего жесты и пружины, поэтому механика вынесена в чистый
//! crate и проверяется формулами на ПК. Внешнего вида здесь нет (это `ui-render-vulkan`, сессия 11),
//! готовых элементов тоже (это `ui-kit`, решение 84). Источник чисел — спецификация
//! `docs/ios-camera/` (сессия 09); у каждого значения по умолчанию в коде указан источник и метка
//! происхождения (`[doc]`, `[review]`, `[reverse]`, `[derived]`, `[estimate]`), оценки — параметры
//! с пометкой «подгонка, не Apple».
//!
//! # Правила
//! * **Единицы — pt.** Пиксели касания переводятся на входе ([`input::PointScale`], решение 82).
//! * **Время — снаружи.** Внутри нет `Instant::now()`: касания несут свою метку, кадры — время vsync
//!   ([`time`]). Один и тот же поток касаний и кадров даёт побитово одинаковый результат.
//! * **Обработчики — намерения.** Жест сообщает «распознан жест с таким-то намерением» событием,
//!   замыканий с захватом чужого состояния нет. Дерево и намерения принадлежат экрану
//!   (`camera-screen`), `ui-core` даёт механизм.
//!
//! # Состав
//! * [`geometry`] — точки, векторы, прямоугольники в pt;
//! * [`time`] — длительности, часы анимаций, задел Reduce Motion;
//! * [`input`] — касания в pt, правило масштаба;
//! * [`id`] — идентификаторы элементов с поколением;
//! * [`spring`] — пружины iOS: аналитическое решение, прерывание с наследованием скорости;
//! * [`scroll`] — прокрутка: замедление, проекция броска, прилипание, «резинка»;
//! * [`velocity`] — оценка скорости пальца по истории касаний;
//! * [`gesture`] — распознаватели жестов и арбитраж как в UIKit;
//! * [`tree`] — дерево элементов, свойства, хит-тест;
//! * [`layout`] — вёрстка якорями и стеками;
//! * [`animator`] — свойства элементов едут пружинами, прерывание, Reduce Motion;
//! * [`scene`] — сцена экрана: дерево + жесты + анимации + часы, вход в пикселях.

pub mod animator;
pub mod geometry;
pub mod gesture;
pub mod id;
pub mod input;
pub mod layout;
pub mod scene;
pub mod scroll;
pub mod spring;
pub mod time;
pub mod tree;
pub mod velocity;
