//! Аниматор свойств элементов: «свойство едет пружиной» (`docs/ios-camera/motion.md` 1.4).
//!
//! Механизм, которым пользуются панели, кнопки и рамка фокуса (`ui-kit`, сессии 11–12):
//! * [`PropertyAnimator`] хранит по одной пружинной анимации на пару «элемент + свойство»
//!   ([`PropertyKey`]);
//! * новая цель для уже едущего свойства — **прерывание как в iOS**: движение продолжается от
//!   текущих положения и скорости, скачка нет ([`StartVelocity::Inherit`]); скорость пальца можно
//!   передать явно ([`StartVelocity::Explicit`]);
//! * [`PropertyAnimator::advance`] применяет значения к [`crate::tree::UiTree`], успокоившиеся
//!   анимации снимает и возвращает [`AdvanceReport`] (сколько применено, успокоено, обрезано,
//!   пропущено из-за мёртвых элементов);
//! * [`PropertyAnimator::forget`] снимает анимации удалённых элементов.
//!
//! # Политика перелёта (упругая пружина выходит за допустимый диапазон)
//! Дерево отвергает прозрачность вне `[0, 1]` ([`crate::tree::TreeError::InvalidOpacity`]). Упругая
//! пружина к цели `1,0` честно уходит выше единицы, а затем возвращается. Решение: **обрезать при
//! применении к дереву**, а саму пружину не трогать — её положение и скорость остаются физическими,
//! поэтому прерывание посреди перелёта по-прежнему непрерывно. Обрезанные значения считаются в
//! [`AdvanceReport::clamped_to_range`]. Допустимость цели проверяется при старте анимации
//! ([`AnimatorError::TargetOutOfRange`]): перелёт — следствие пружины, а неверная цель — ошибка вызова.
//!
//! # Reduce Motion
//! При [`MotionPreference::Reduced`] пружина с `bounce > 0` заменяется на пружину той же длительности
//! с `bounce = 0` (критическое затухание), а значение дополнительно удерживается внутри отрезка
//! «от текущего до цели»: даже большая начальная скорость не даст перелёта.

