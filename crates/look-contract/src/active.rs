//! Что библиотека пресетов отдаёт наружу: текущий вид и откуда он взялся.

use crate::preset::PresetId;
use crate::recipe::LookRecipe;

/// Совпадает ли текущий вид со значениями активного пресета.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EditState {
    /// Значения ровно как у активного пресета.
    Clean,
    /// Владелец покрутил ручки поверх активного пресета и пока не сохранил.
    EditedOnTop,
}

/// Текущий вид: активный пресет, итоговый рецепт и рецепт самого пресета.
#[derive(Debug, Clone, PartialEq)]
pub struct ActiveLook {
    /// Активный пресет.
    pub preset: PresetId,
    /// Итоговый рецепт (с учётом правок): основа и значения ручек. Именно он уходит рендеру и в запрос снимка.
    pub recipe: LookRecipe,
    /// Рецепт активного пресета БЕЗ правок: к нему сбрасывается одна ручка (решение 196), по нему
    /// экран видит, какие ручки отличаются от пресета.
    pub preset_recipe: LookRecipe,
    /// Есть ли правки поверх пресета.
    pub edits: EditState,
}
