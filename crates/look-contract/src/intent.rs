//! Намерения экрана: экран ничего не считает и не пишет на диск, он только шлёт их исполнителю.

use crate::bands::HueBandId;
use crate::control::{BandAxis, GlobalKnob, LookControl};
use crate::knob::LookKnob;
use crate::preset::{PresetId, PresetName, UserPresetId};
use crate::settings::LookSettings;
use crate::tone_base::ToneBaseModel;

/// Что владелец хочет сделать с видом или пресетами.
#[derive(Debug, Clone, PartialEq)]
pub enum LookIntent {
    /// «Вид = эти значения»: правки ручек поверх активного пресета (пресет не меняется).
    /// Основа остаётся текущей: её меняет [`LookIntent::SetToneBase`].
    SetLook(LookSettings),
    /// «Эта ручка = это значение» поверх ТЕКУЩЕГО вида библиотеки; остальные ручки не трогаются.
    ///
    /// Точечное намерение, а не полный набор значений: экран строит его, не зная остальных ручек. Иначе два жеста в
    /// одном кадре (два пальца на разных ручках) несли бы оба набор из одних и тех же устаревших фактов, и второй
    /// затёр бы первый (найдено ревью 14b). Применяет библиотека — единственный владелец значений.
    SetKnob {
        /// Какая ручка.
        knob: GlobalKnob,
        /// Новое значение.
        value: LookKnob,
    },
    /// «Эта ось этой полосы = это значение» поверх текущего вида; другие оси и полосы не трогаются. Причина та же,
    /// что у [`LookIntent::SetKnob`].
    SetBandAxis {
        /// Какая полоса (id из каталога полос; неизвестная полоса — отказ библиотеки `UnknownControl`).
        band: HueBandId,
        /// Какая ось полосы.
        axis: BandAxis,
        /// Новое значение.
        value: LookKnob,
    },
    /// Сменить модель основы поверх активного пресета (решение 195): такая же правка, как поворот ручки.
    SetToneBase(ToneBaseModel),
    /// Вернуть один орган управления к значению ПРАВЛЕННОГО пресета, а не к нулю (решение 196).
    /// Остальные правки остаются.
    ResetControl(LookControl),
    /// Выбрать пресет: он становится активным, правки поверх сбрасываются.
    SelectPreset(PresetId),
    /// Сохранить текущий вид как новый свой пресет с этим именем; он становится активным.
    SaveAsNewPreset(PresetName),
    /// Переименовать свой пресет.
    RenamePreset {
        /// Какой пресет.
        preset: UserPresetId,
        /// Новое имя.
        name: PresetName,
    },
    /// Записать текущий вид в свой пресет (перезаписать его значения).
    OverwritePreset(UserPresetId),
    /// Удалить свой пресет.
    DeletePreset(UserPresetId),
    /// Отбросить правки поверх: вернуть значения активного пресета.
    DiscardEdits,
}

/// Какой вид показывает видоискатель: «чистая» картинка или с правками (решение 189, кнопка «показать основу»).
///
/// Это ТОЛЬКО режим показа на экране. Он НЕ трогает библиотеку пресетов: правки, активный пресет и основа остаются
/// как были, ничего не сохраняется и не откатывается. Отпустил кнопку — видоискатель снова показывает правленый вид.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum CleanView {
    /// Показать основу без ручек: значения вида нейтральные, модель основы действующая. Пока кнопка зажата, смена
    /// основы всё равно видна сразу, а правки ручек применяются после отпускания.
    ShowBase,
    /// Показать вид с правками (обычный режим).
    #[default]
    ShowEdited,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_default_clean_view_is_the_edited_look_and_the_two_modes_differ() {
        assert_eq!(CleanView::default(), CleanView::ShowEdited);
        assert_ne!(CleanView::ShowBase, CleanView::ShowEdited);
    }
}
