//! Различимые ошибки пресетов: экран по варианту решает, что показать.

use crate::control::LookControl;
use crate::preset::{BuiltinPreset, PresetId};

/// Сбой хранилища: какая именно операция и текстовая причина.
///
/// Своё перечисление, а не `std::io::Error`: словарь обязан быть `Clone + PartialEq`
/// (ошибки пересылаются между потоками и сравниваются в тестах). Причина — текст
/// исходной ошибки ОС.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum StorageFailure {
    /// Файл существует, но прочитать его не удалось.
    #[error("не удалось прочитать файл пресетов: {0}")]
    ReadFailed(String),
    /// Не удалось создать временный файл рядом с основным.
    #[error("не удалось создать временный файл пресетов: {0}")]
    CreateTempFailed(String),
    /// Не удалось записать данные во временный файл.
    #[error("не удалось записать временный файл пресетов: {0}")]
    WriteFailed(String),
    /// Не удалось сбросить временный файл на диск.
    #[error("не удалось сбросить временный файл пресетов на диск: {0}")]
    SyncFailed(String),
    /// Не удалось заменить основной файл временным.
    #[error("не удалось заменить файл пресетов: {0}")]
    ReplaceFailed(String),
    /// Не удалось сбросить каталог на диск после замены.
    #[error("не удалось сбросить каталог пресетов на диск: {0}")]
    SyncDirectoryFailed(String),
    /// Не удалось сериализовать состояние в JSON.
    #[error("не удалось сериализовать пресеты: {0}")]
    SerializeFailed(String),
    /// Испорченный файл не удалось убрать в сторону, поэтому запись запрещена, чтобы его не затереть.
    #[error("запись пресетов запрещена, чтобы не затереть непрочитанный файл: {0}")]
    SavesRefused(String),
    /// Не удалось сохранить резервную копию файла старой схемы перед первой записью после миграции
    /// (запись отказана, чтобы не затереть единственный экземпляр старого файла).
    #[error("не удалось сохранить резервную копию файла пресетов старой схемы: {0}")]
    BackupFailed(String),
    /// Кончились идентификаторы пользовательских пресетов.
    #[error("кончились идентификаторы пользовательских пресетов")]
    IdSpaceExhausted,
}

/// Ошибка операции над пресетами. Варианты НЕ сливаются: у каждого своя реакция экрана.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PresetError {
    /// Имя уже занято (другим своим пресетом или именем встроенного), без учёта регистра.
    #[error("имя пресета уже занято")]
    NameTaken,
    /// Пресета с таким идентификатором нет.
    #[error("пресет не найден: {0:?}")]
    NotFound(PresetId),
    /// Встроенный пресет нельзя переименовать, перезаписать или удалить.
    #[error("встроенный пресет {0:?} нельзя изменить")]
    BuiltinIsReadOnly(BuiltinPreset),
    /// Орган управления не существует: полосы с таким идентификатором нет в каталоге.
    #[error("нет такого органа управления: {0:?}")]
    UnknownControl(LookControl),
    /// Сбой хранилища.
    #[error("сбой хранилища пресетов: {0}")]
    Storage(StorageFailure),
}
