//! Правило возобновления белого (план `user/white-balance`, сессия 03, решение WB36).
//!
//! Что делать с белой, когда приложение возвращается из фона. Это ЕДИНСТВЕННОЕ место, где живёт такое правило:
//! читает его только `WhiteOwner::on_foreground`, больше никто (экран, рендер и память решения не принимают).

use camera_contract::white::WhiteOrigin;
use serde::{Deserialize, Serialize};

/// Правило возобновления белого. Работает только при возврате приложения из фона: смена линзы, потеря потока
/// и пауза потока белую не трогают ни при каком правиле.
///
/// В JSON — простая строка (`"resume_rule": "keep_last"`), как у `FlickerPolicy`: у строки не бывает лишних
/// полей, а неизвестное значение отвергается разбором с именем поля.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WhiteResumeRule {
    /// Вернулся в приложение, белая не ручная — берётся у источника открытия («телефон»), первые кадры скрыты
    /// до ответа (WB22). По умолчанию (решение владельца WB37): быстрый кадр в незнакомом свете без действий.
    #[default]
    TakeFromSource,
    /// Белая сама не меняется: при возобновлении держится последняя, любого происхождения. Источник
    /// спрашивается только по просьбе человека (долгое нажатие, «Phone»). Для съёмки под монтаж: клипы одной
    /// сцены не расходятся по цвету. Единственное исключение — белая запасного света ([`WhiteOrigin::Fallback`]):
    /// это не выбор человека, а заглушка, пока никто белую не называл (самый первый запуск, WB38; телефон не
    /// ответил на первом запуске, WB39), поэтому её при возобновлении спрашивают у источника.
    KeepLast,
}

impl WhiteResumeRule {
    /// Надо ли при возобновлении завести заявку источнику открытия (и скрыть кадры до ответа), если сейчас
    /// действует белая с происхождением `held_origin`.
    ///
    /// Ручная белая держится при любом правиле: рука сильнее источника.
    pub const fn asks_source_on_resume(self, held_origin: WhiteOrigin) -> bool {
        match (self, held_origin) {
            (_, WhiteOrigin::Manual) => false,
            (Self::TakeFromSource, _) => true,
            (Self::KeepLast, WhiteOrigin::Fallback) => true,
            (Self::KeepLast, WhiteOrigin::Source(_)) => false,
        }
    }
}

/// Итог выбора правила для вызывающего (команда `SetWhiteResumeRule`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResumeRuleChoice {
    /// Выбор человека записан (в том числе значение, совпавшее с умолчанием конфига: это всё равно выбор,
    /// и его запоминаем).
    Chosen,
    /// Человек уже выбрал именно это правило: ничего не изменилось.
    AlreadyChosen,
}
