//! `photo-output` — файлы снимков (README «Владельцы состояния»: «Файлы снимков — `photo-output`,
//! не знает про UI»).
//!
//! Что здесь живёт:
//! * [`tiff`] — минимальный писатель TIFF 6.0 (little-endian `II`): IFD, типы полей, вложенные IFD;
//! * [`dng`] — своя clean-room запись DNG по спецификации DNG 1.7 (номера разделов — в комментариях);
//! * [`exif`] — блок Exif для HEIF и JPEG (тот же писатель TIFF);
//! * [`jpeg_exif`] — вставка Exif (APP1) в поток JPEG от платформы;
//! * [`service`] — служба записи снимков на своём рабочем потоке: принимает события проявления от
//!   рендера, открывает черновики в хранилище и кодеры через сервисы оболочки, пишет DNG, публикует файлы
//!   и сообщает фазы снимка.
//!
//! Чего здесь нет: GPU, Android, UI. Платформенные сервисы — трейты `shell-contract::still_media`,
//! словарь снимка — `still-contract`.

pub mod dng;
pub mod exif;
pub mod jpeg_exif;
pub mod service;
pub mod tiff;
